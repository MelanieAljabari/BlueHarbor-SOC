#!/bin/bash

MATCHES=$(sudo journalctl --since today --no-pager | grep -Ei "failed password|authentication failure|invalid user")

if [ -n "$MATCHES" ]; then
    echo "ALERT: Failed authentication detected"
    echo "$MATCHES"
else
    echo "No failed authentication detected"
fi














































































































































































